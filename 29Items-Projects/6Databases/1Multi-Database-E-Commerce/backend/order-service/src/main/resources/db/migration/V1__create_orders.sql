-- ============================================================================
-- V1: order-service transactional schema (Oracle).
-- Owned exclusively by order-service; no other service touches these tables.
-- ============================================================================

CREATE TABLE ORDERS (
    ID            VARCHAR2(36)   NOT NULL,
    CUSTOMER_ID   VARCHAR2(64)   NOT NULL,
    STATUS        VARCHAR2(20)   NOT NULL,
    CURRENCY      VARCHAR2(3)    NOT NULL,
    TOTAL_AMOUNT  NUMBER(19,4)   NOT NULL,
    CREATED_AT    TIMESTAMP(6)   NOT NULL,
    VERSION       NUMBER(19)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ORDERS PRIMARY KEY (ID),
    CONSTRAINT CK_ORDERS_STATUS CHECK (STATUS IN ('PENDING','PAID','FULFILLED','CANCELLED')),
    CONSTRAINT CK_ORDERS_TOTAL  CHECK (TOTAL_AMOUNT >= 0)
);

CREATE TABLE ORDER_ITEMS (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ORDER_ID    VARCHAR2(36)  NOT NULL,
    PRODUCT_ID  VARCHAR2(64)  NOT NULL,
    QUANTITY    NUMBER(10)    NOT NULL,
    UNIT_PRICE  NUMBER(19,4)  NOT NULL,
    CONSTRAINT PK_ORDER_ITEMS PRIMARY KEY (ID),
    CONSTRAINT FK_ITEMS_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_ITEMS_QTY   CHECK (QUANTITY > 0),
    CONSTRAINT CK_ITEMS_PRICE CHECK (UNIT_PRICE > 0)
);

-- Hot read path: a customer's order history, newest first.
CREATE INDEX IX_ORDERS_CUSTOMER ON ORDERS (CUSTOMER_ID, CREATED_AT DESC);
CREATE INDEX IX_ITEMS_ORDER     ON ORDER_ITEMS (ORDER_ID);
